class AuditLog(Base):
    """
    Immutable audit log with hash chain.

    RGPD Art. 30: Register of processing activities
    RGPD Art. 5.2: Accountability principle
    NIS2 Art. 21.2.f: Verification of security measures

    Hash chain (previous_hash -> current_hash) computed by BEFORE INSERT trigger.
    UPDATE and DELETE blocked by triggers (immutability).
    """

    __tablename__ = "audit_log"

    id: Mapped[UUID] = mapped_column(
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )
    sequence_number: Mapped[int | None] = mapped_column(
        BigInteger,
        unique=True,
        # BIGSERIAL - auto-generated by database sequence
    )

    # Actor
    user_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )

    # Action
    action: Mapped[str] = mapped_column(String(50), nullable=False)
    entity_type: Mapped[str] = mapped_column(String(50), nullable=False)
    entity_id: Mapped[UUID | None] = mapped_column(nullable=True)

    # Change details
    changed_fields: Mapped[dict | None] = mapped_column(JSONB, nullable=True)
    change_summary: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Context
    ip_address: Mapped[str | None] = mapped_column(INET, nullable=True)
    ip_anonymized: Mapped[bool] = mapped_column(
        Boolean,
        server_default=text("false"),
    )
    ip_retention_justification: Mapped[str | None] = mapped_column(
        String(100),
        server_default=text("'security_fraud_prevention'"),
    )
    ip_anonymization_date: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    user_agent: Mapped[str | None] = mapped_column(Text, nullable=True)
    request_id: Mapped[str | None] = mapped_column(String(100), nullable=True)
    session_id: Mapped[UUID | None] = mapped_column(nullable=True)

    # Classification
    severity: Mapped[str | None] = mapped_column(
        String(20),
        server_default=text("'info'"),
    )
    details: Mapped[dict | None] = mapped_column(
        JSONB,
        server_default=text("'{}'"),
    )
    risk_level: Mapped[str | None] = mapped_column(String(20), nullable=True)
    legal_basis: Mapped[str | None] = mapped_column(String(100), nullable=True)

    # Integrity (computed by audit_log_hash_trigger BEFORE INSERT)
    previous_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    current_hash: Mapped[str | None] = mapped_column(
        String(64),
        # NOT NULL in SQL, but auto-computed by BEFORE INSERT trigger
    )
    timestamp_signature: Mapped[str | None] = mapped_column(
        String(128),
        # NOT NULL in SQL, but auto-computed by BEFORE INSERT trigger
    )

    # Timestamp
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.current_timestamp(),
        nullable=False,
    )

    __table_args__ = (
        CheckConstraint(
            "action IN ('INSERT', 'UPDATE', 'DELETE', 'LOGIN', 'LOGOUT', "
            "'FAILED_LOGIN', 'PASSWORD_CHANGE', 'PERMISSION_CHANGE', "
            "'DATA_EXPORT', 'DATA_DELETE', 'CONSENT_GIVEN', 'CONSENT_REVOKED', "
            "'DATA_ACCESS_REQUEST', 'KEY_ROTATION', 'RATE_LIMIT_EXCEEDED', "
            "'MFA_ENABLED', 'MFA_DISABLED', 'DELETION_REQUEST_CREATED', "
            "'SYSTEM_ALERT', 'BREACH_REGISTERED', 'BREACH_NOTIFICATION_SENT', "
            "'SENSITIVE_DATA_DETECTED', 'DATA_BLOCK', 'GDPR_ERASURE_WITH_BLOCKING', "
            "'AI_TRANSPARENCY_WARNING', 'AI_DECISION_LOGGED', "
            "'AI_ACT_VIOLATION_BLOCKED', 'ROBINSON_CHECK')",
            name="audit_log_action_check",
        ),
        CheckConstraint(
            "severity IN ('debug', 'info', 'warning', 'error', 'critical')",
            name="audit_log_severity_check",
        ),
        CheckConstraint(
            "risk_level IS NULL OR risk_level IN ('low', 'medium', 'high', 'critical')",
            name="audit_log_risk_level_check",
        ),
        Index("idx_audit_user", "user_id", "created_at"),
        Index("idx_audit_entity", "entity_type", "entity_id", "created_at"),
        Index("idx_audit_action", "action", "created_at"),
        Index(
            "idx_audit_severity",
            "severity",
            "created_at",
            postgresql_where="severity IN ('error', 'critical')",
        ),
    )


class SecurityBreach(Base):
    """
    Security breach tracking. Maps to sferaai.sql line 6430.

    RGPD Art. 33: Notification to authority within 72 hours
    RGPD Art. 34: Communication to data subjects
    NIS2 Art. 23: Incident reporting
    """

    __tablename__ = "security_breaches"

    id: Mapped[UUID] = mapped_column(
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )

    # Incident information
    breach_reference: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        unique=True,
        comment="Internal reference (e.g. BREACH-2025-001)",
    )
    breach_title: Mapped[str] = mapped_column(String(255), nullable=False)
    breach_description: Mapped[str] = mapped_column(Text, nullable=False)
    breach_type: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        comment="confidentiality, integrity, availability, mixed",
    )

    # Severity classification
    severity: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        comment="low, medium, high, critical",
    )

    # Timeline (Art. 33.1: max 72 hours)
    detected_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )
    confirmed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    contained_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    resolved_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Legal deadlines
    authority_notification_deadline: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        comment="detected_at + 72 hours",
    )
    authority_notified_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    authority_notification_reference: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        comment="AEPD reference number",
    )

    # Risk assessment for data subjects (Art. 34.1)
    risk_level: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        comment="unlikely, possible, likely, high",
    )
    users_notification_required: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        server_default=text("false"),
        comment="Art. 34: Notify data subjects?",
    )
    users_notified_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Affected data
    affected_records_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default=text("0"),
    )
    affected_records_estimated: Mapped[bool | None] = mapped_column(
        Boolean,
        server_default=text("false"),
    )
    data_categories_affected: Mapped[list] = mapped_column(
        ARRAY(String),
        nullable=False,
        server_default=text("'{}'"),
        comment="email, phone, name, financial, etc.",
    )
    special_categories_affected: Mapped[bool | None] = mapped_column(
        Boolean,
        server_default=text("false"),
        comment="Art. 9: Sensitive data (health, ethnicity, etc.)",
    )

    # Cause and attack vector
    breach_cause: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        comment="external_attack, internal_error, lost_device, unauthorized_access",
    )
    attack_vector: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Measures taken (Art. 33.3.d)
    containment_measures: Mapped[str | None] = mapped_column(Text, nullable=True)
    remediation_measures: Mapped[str | None] = mapped_column(Text, nullable=True)
    preventive_measures: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Process status
    status: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        server_default=text("'detected'"),
        comment="detected, investigating, confirmed, contained, "
        "authority_notified, users_notified, resolved, closed",
    )

    # Responsible
    detected_by: Mapped[UUID | None] = mapped_column(
        ForeignKey("users.id"),
        nullable=True,
    )
    assigned_to: Mapped[UUID | None] = mapped_column(
        ForeignKey("users.id"),
        nullable=True,
    )
    dpo_notified_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Documentation
    internal_report_url: Mapped[str | None] = mapped_column(Text, nullable=True)
    authority_report_url: Mapped[str | None] = mapped_column(Text, nullable=True)
    lessons_learned: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Metadata
    extra_metadata: Mapped[dict | None] = mapped_column(
        "metadata",
        JSONB,
        server_default=text("'{}'"),
    )

    # Timestamps
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.current_timestamp(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.current_timestamp(),
        onupdate=func.current_timestamp(),
    )

    __table_args__ = (
        CheckConstraint(
            "breach_type IN ('confidentiality', 'integrity', 'availability', 'mixed')",
            name="breaches_type_check",
        ),
        CheckConstraint(
            "severity IN ('low', 'medium', 'high', 'critical')",
            name="breaches_severity_check",
        ),
        CheckConstraint(
            "status IN ('detected', 'investigating', 'confirmed', 'contained', "
            "'authority_notified', 'users_notified', 'resolved', 'closed')",
            name="breaches_status_check",
        ),
        CheckConstraint(
            "risk_level IN ('unlikely', 'possible', 'likely', 'high')",
            name="breaches_risk_check",
        ),
        Index("idx_breaches_status", "status", "detected_at"),
        Index("idx_breaches_severity", "severity", "status"),
        Index("idx_breaches_reference", "breach_reference"),
        Index(
            "idx_breaches_deadline",
            "authority_notification_deadline",
            postgresql_where="authority_notified_at IS NULL",
        ),
    )


class BlockedData(Base):
    """
    Blocked data storage (LOPDGDD Art. 33).

    When data is requested for deletion but must be retained for legal obligations,
    it is moved here with restricted access (only judicial authorities).
    """

    __tablename__ = "blocked_data"

    id: Mapped[UUID] = mapped_column(
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )

    # Original data reference
    original_table: Mapped[str] = mapped_column(String(100), nullable=False)
    original_id: Mapped[UUID] = mapped_column(nullable=False)
    original_id_secondary: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
    )

    # Blocked data (encrypted)
    data_encrypted: Mapped[bytes] = mapped_column(
        LargeBinary,
        nullable=False,
        comment="AES-256 encrypted copy of data",
    )
    data_encryption_key_id: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
    )
    data_hash: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        comment="SHA-256 hash for integrity",
    )

    # Timing
    blocked_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.current_timestamp(),
        nullable=False,
    )

    # Blocking reason (LOPDGDD Art. 33.2)
    block_reason: Mapped[str] = mapped_column(
        String(500),
        nullable=False,
    )
    block_legal_basis: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        comment="Specific law/article requiring retention",
    )

    # References
    deletion_request_id: Mapped[UUID | None] = mapped_column(nullable=True)
    data_subject_id: Mapped[UUID | None] = mapped_column(nullable=True)
    data_subject_type: Mapped[str | None] = mapped_column(
        String(50),
        nullable=True,
    )

    # Unblock/destruction date (LOPDGDD Art. 33.4)
    unblock_date: Mapped[date] = mapped_column(
        Date,
        nullable=False,
        comment="When blocked data can be destroyed",
    )
    unblock_reason: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # Status
    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        server_default=text("'blocked'"),
    )

    # Access control (LOPDGDD Art. 33.3)
    accessible_by: Mapped[list | None] = mapped_column(
        ARRAY(String(100)),
        server_default=text("ARRAY['JUDGES','PROSECUTORS','COMPETENT_AUTHORITIES']"),
        comment="Restricted access: judicial/administrative authorities only",
    )

    # Access log
    access_log: Mapped[list | None] = mapped_column(
        JSONB,
        server_default=text("'[]'"),
        comment="Log of all accesses to blocked data",
    )

    # Audit
    created_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        server_default=func.current_timestamp(),
    )
    created_by: Mapped[UUID | None] = mapped_column(nullable=True)
    destroyed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    destroyed_by: Mapped[UUID | None] = mapped_column(nullable=True)

    __table_args__ = (
        CheckConstraint(
            "status IN ('blocked', 'accessed', 'destroyed')",
            name="blocked_data_status_check",
        ),
        UniqueConstraint("original_table", "original_id", name="unique_blocked_record"),
        Index("idx_blocked_original", "original_table", "original_id"),
        Index("idx_blocked_subject", "data_subject_id", "data_subject_type"),
        Index("idx_blocked_unblock_date", "unblock_date", postgresql_where="status = 'blocked'"),
        Index("idx_blocked_status", "status"),
    )


class DataSubjectRequest(Base):
    """
    GDPR rights requests (ARSOPL).

    RGPD Art. 12.3: Response within 1 month
    RGPD Art. 15-22: Various rights
    """

    __tablename__ = "data_subject_requests"

    id: Mapped[UUID] = mapped_column(
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )

    # Requester
    requester_type: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        comment="user, contact, representative",
    )
    requester_id: Mapped[UUID | None] = mapped_column(nullable=True)
    requester_email: Mapped[str | None] = mapped_column(String(255), nullable=True)
    requester_phone: Mapped[str | None] = mapped_column(String(50), nullable=True)

    # Identity verification (RGPD Art. 12.6)
    identity_verified: Mapped[bool] = mapped_column(Boolean, default=False)
    verification_method: Mapped[str | None] = mapped_column(String(50), nullable=True)
    verification_date: Mapped[datetime | None] = mapped_column(nullable=True)

    # Request details
    request_type: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        comment="access, rectification, erasure, restriction, portability, objection",
    )
    request_details: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Timing (RGPD Art. 12.3)
    received_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )
    response_due_date: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        comment="received_at + 1 month",
    )
    extended_deadline: Mapped[datetime | None] = mapped_column(
        nullable=True,
        comment="Can extend by 2 months for complex requests",
    )
    extension_reason: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Processing
    assigned_to: Mapped[UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    status: Mapped[str] = mapped_column(
        String(30),
        default="pending",
        comment="pending, in_progress, completed, rejected, cancelled",
    )

    # Response
    responded_at: Mapped[datetime | None] = mapped_column(nullable=True)
    response_type: Mapped[str | None] = mapped_column(
        String(30),
        nullable=True,
        comment="fulfilled, partially_fulfilled, denied, no_data_found",
    )
    response_details: Mapped[str | None] = mapped_column(Text, nullable=True)
    denial_reason: Mapped[str | None] = mapped_column(Text, nullable=True)

    # For export requests (Art. 15, 20)
    export_file_path: Mapped[str | None] = mapped_column(Text, nullable=True)
    export_format: Mapped[str | None] = mapped_column(String(20), nullable=True)
    export_expires_at: Mapped[datetime | None] = mapped_column(nullable=True)

    # Audit
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.current_timestamp(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.current_timestamp(),
        onupdate=func.current_timestamp(),
    )

    __table_args__ = (
        CheckConstraint(
            "request_type IN ('access', 'rectification', 'erasure', "
            "'restriction', 'portability', 'objection', 'automated_decision')",
            name="dsr_type_check",
        ),
        CheckConstraint(
            "status IN ('pending', 'in_progress', 'completed', 'rejected', 'cancelled')",
            name="dsr_status_check",
        ),
        Index("idx_dsr_requester", "requester_type", "requester_id"),
        Index("idx_dsr_status", "status"),
        Index(
            "idx_dsr_due_date",
            "response_due_date",
            postgresql_where="status IN ('pending', 'in_progress')",
        ),
        Index("idx_dsr_type", "request_type"),
    )
